#!/usr/bin/env python3
"""Regenerate explicit Kubernetes bootstrap pack data and its OCaml embedding.

Requires an already built, pinned native reference oracle. Never downloads,
contacts a cluster, changes contracts or derives access requirements.
"""
import argparse
import hashlib
import json
import subprocess
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference', required=True, type=Path)
    parser.add_argument('--check', action='store_true', help='verify both generated files without writing')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[3]
    result = subprocess.run([str(args.reference.resolve()), '--bootstrap-pack-reference'],
                            check=True, capture_output=True, timeout=30)
    data = result.stdout
    value = json.loads(data)
    if value['kubernetes_version'] != '1.34.0' or value['kind'] != 'kubernetes-bootstrap-reference-packs':
        raise ValueError('Unexpected native artifact')
    if b'|bootstrap_packs}' in data or not data.endswith(b'\n') or data.endswith(b'\n\n'):
        raise ValueError('Unsafe OCaml delimiter or noncanonical final newline')
    digest = hashlib.sha256(data).hexdigest()
    embedded = ('(* Generated by bench/kubernetes-rbac/bootstrap-packs/generate.py.\n'
                '   Derived Kubernetes policy: Apache-2.0; see bootstrap-packs/KUBERNETES-LICENSE.\n'
                '   Do not edit this file independently of its pinned native source. *)\n'
                'let sha256 = "' + digest + '"\n'
                'let json = {bootstrap_packs|' + data.decode() + '|bootstrap_packs}\n').encode()
    outputs = {root/'bench/kubernetes-rbac/bootstrap-packs/kubernetes-v1.34.0.json': data,
               root/'connectors/kubernetes_rbac/bootstrap_data.ml': embedded}
    for path, expected in outputs.items():
        if args.check:
            if path.read_bytes() != expected:
                raise ValueError('Generated bootstrap data differs: '+str(path))
        else:
            path.write_bytes(expected)
    print(json.dumps({'verified' if args.check else 'generated': [str(p.relative_to(root)) for p in outputs],
                      'source_sha256': digest}))


if __name__ == '__main__':
    main()
